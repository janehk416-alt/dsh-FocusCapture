import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('./',import.meta.url);
const source = await readFile(new URL('client.source.js',root),'utf8');
const delivery = (await readFile(new URL('delivery.js',root),'utf8')).replace('export function attachScreenshot','function attachScreenshot');
const config = await readFile(new URL('config.source.js',root),'utf8');
if (!source.includes('/* INSERT_DELIVERY */') || !source.includes('/* INSERT_CONFIG */')) throw new Error('Missing Client insertion placeholder');
await writeFile(new URL('client.js',root),'// Generated by build-client.mjs from client.source.js, delivery.js and config.source.js.\n'+source.replace('/* INSERT_DELIVERY */',delivery).replace('/* INSERT_CONFIG */',config));
console.log('Built client.js (no dependencies)');
