import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('./',import.meta.url);
const source = await readFile(new URL('client.source.js',root),'utf8');
const delivery = (await readFile(new URL('delivery.js',root),'utf8')).replace('export function attachScreenshot','function attachScreenshot');
if (!source.includes('/* INSERT_DELIVERY */')) throw new Error('Missing delivery placeholder');
await writeFile(new URL('client.js',root),'// Generated by build-client.mjs from client.source.js and delivery.js.\n'+source.replace('/* INSERT_DELIVERY */',delivery));
console.log('Built client.js (no dependencies)');
